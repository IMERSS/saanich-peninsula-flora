#!/usr/bin/env bash
# Copy the bioReportR "framework" files from this project into another bioReportR project.
#
# Usage: ./copyFramework.sh [-n] <target-project-dir>
#   -n   Dry run - report what would change without copying anything
#
# Deliberately NOT copied:
#  - Files produced by the config.json5 copyJobs (static/imerss-bioinfo/*, static/inat-components/*,
#    static/bioreportr/img/download.svg) - regenerate these in the target with "npm run build"
#  - Project-local content and configuration: config.json5, hugo.yaml, package.json, mapboxData.json, content/,
#    layouts/partials/custom/head-end.html, layouts/partials/favicons.html, static/local/ (including
#    static/local/js/<project>.js, e.g. saanich.js, howe.js),
#    R/build.R (lists the project's data files), scripts/*.R map and analysis scripts
#  - Experimental R parsing work: src/js/parseR.mjs, src/js/r-parser/
#  - Generated output: layouts/story/single.html (written by reknit from src/html/template.html), docs/

set -euo pipefail

DRY_RUN=0
if [ "${1:-}" = "-n" ]; then
    DRY_RUN=1
    shift
fi

if [ $# -ne 1 ]; then
    echo "Usage: $0 [-n] <target-project-dir>" >&2
    exit 1
fi

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TARGET="$(cd "$1" && pwd)"

if [ "$SRC" = "$TARGET" ]; then
    echo "Target is the same as the source project" >&2
    exit 1
fi

if [ ! -f "$TARGET/config.json5" ] || [ ! -f "$TARGET/src/js/reknit.js" ]; then
    echo "$TARGET does not look like a bioReportR project (no config.json5 or src/js/reknit.js)" >&2
    exit 1
fi

FILES=(
    # Ourselves
    copyFrameworkOut.sh
    # Node-side reknitting pipeline
    index.js
    src/js/reknit.js
    src/js/utils.js
    src/json/stylesNonMapbox.json
    src/json/provenance.txt

    # HTML template consumed by reknit
    src/html/template.html

    # Client-side story page runtime
    static/bioreportr/js/reknit-client.js
    static/bioreportr/js/imerss-viz-reknit.js
    static/bioreportr/js/paneHandlers.js
    static/bioreportr/js/solowControls.js

    # Vendored client libraries not managed by copyJobs
    static/bioreportr/js/htmlwidgets.js
    static/bioreportr/js/htmlwidgets-plotly.js
    static/bioreportr/js/plotly-2.1.1.js

    # Story page styling
    static/bioreportr/css/imerss-story.css
    static/bioreportr/css/imerss-viz-story.css
    static/bioreportr/css/imerss-blitzr.css
    static/bioreportr/images/imerss-header-cropped.jpg

    # Hugo layout overrides of the hextra theme
    layouts/_default/baseof.html
    layouts/partials/footer.html
    layouts/partials/language-switch.html
    layouts/partials/navbar.html
    layouts/partials/search.html
    layouts/partials/sidebar.html
    layouts/partials/subnav.html
    layouts/partials/toc.html
    layouts/shortcodes/new-feature.html
    layouts/story/single-autogenerated-do-not-edit.txt

    # Shared R: blogdown hooks and map/geometry utilities
    R/build2.R
    R/knit_render.R
    scripts/utils.R
    scripts/geomUtils.R
    scripts/mapbox_map_common.R

    # Lint configuration
    .eslintrc.json
    .fluidlintallrc.json
)

# imerss-viz-reknit.js hardwires the project's taxa filter holder grade (e.g. reknitr.saanichTaxaFiltersHolder,
# reknitr.howeTaxaFiltersHolder) - keep whatever the target currently uses until this is made configurable
HOLDER_FILE=static/bioreportr/js/imerss-viz-reknit.js
HOLDER_PATTERN='reknitr\.[A-Za-z0-9_]*TaxaFiltersHolder'
TARGET_HOLDER=""
if [ -f "$TARGET/$HOLDER_FILE" ]; then
    TARGET_HOLDER="$(grep -oE "type: \"$HOLDER_PATTERN\"" "$TARGET/$HOLDER_FILE" | head -1 | sed -E 's/type: "(.*)"/\1/' || true)"
fi
SOURCE_HOLDER="$(grep -oE "type: \"$HOLDER_PATTERN\"" "$SRC/$HOLDER_FILE" | head -1 | sed -E 's/type: "(.*)"/\1/' || true)"

new=0
changed=0
unchanged=0
for f in "${FILES[@]}"; do
    if [ ! -f "$SRC/$f" ]; then
        echo "MISSING in source: $f" >&2
        exit 1
    fi
    if [ ! -f "$TARGET/$f" ]; then
        status="new"
        new=$((new + 1))
    elif cmp -s "$SRC/$f" "$TARGET/$f"; then
        unchanged=$((unchanged + 1))
        continue
    else
        status="changed"
        changed=$((changed + 1))
    fi
    echo "$status: $f"
    if [ $DRY_RUN -eq 0 ]; then
        mkdir -p "$(dirname "$TARGET/$f")"
        cp -p "$SRC/$f" "$TARGET/$f"
    fi
done

if [ -n "$TARGET_HOLDER" ] && [ -n "$SOURCE_HOLDER" ] && [ "$TARGET_HOLDER" != "$SOURCE_HOLDER" ]; then
    echo "Preserving target's $TARGET_HOLDER in $HOLDER_FILE (source uses $SOURCE_HOLDER)"
    if [ $DRY_RUN -eq 0 ]; then
        # A backup suffix attached to -i is the only form which both GNU and BSD (macOS) sed accept
        sed -i.bak "s/type: \"$SOURCE_HOLDER\"/type: \"$TARGET_HOLDER\"/" "$TARGET/$HOLDER_FILE"
        rm -f "$TARGET/$HOLDER_FILE.bak"
    fi
fi

echo
echo "$new new, $changed changed, $unchanged unchanged$([ $DRY_RUN -eq 1 ] && echo " (dry run - nothing copied)")"
if [ $DRY_RUN -eq 0 ] && [ $((new + changed)) -gt 0 ]; then
    echo "Now run \"npm run build\" in $TARGET to refresh copyJobs output and regenerate layouts/story/single.html"
fi
