/* eslint-env node */

"use strict";

// Copy the scripts and styles of the hextra theme which Hugo's asset pipeline would otherwise bundle, minify and
// fingerprint, into static/bioreportr/hextra, from which they are published at stable URLs - see
// layouts/partials/scripts.html and layouts/partials/head-css.html, which link to them. Run this again after updating
// the theme in themes/hextra, or after changing the project's override of its menu script, src/hextra/js/menu.js.
// Only one of the theme's scripts is a template, theme.js, whose default colour scheme is filled in from hugo.yaml.
// The theme's search is disabled in hugo.yaml, and its search, mermaid and KaTeX scripts are not copied.
// Usage: node src/js/themeAssets.js
// This is notionally part of the bioReportR package, and is copied between bioReportR projects by copyFrameworkOut.sh

const fs = require("fs"),
    path = require("path"),
    yaml = require("js-yaml");

const projectDir = path.resolve(__dirname, "../..");
const themeAssets = path.join(projectDir, "themes/hextra/assets");
const outDir = path.join(projectDir, "static/bioreportr/hextra");

// The theme's scripts, in the order in which its scripts.html concatenates them
const scripts = ["theme.js", "menu.js", "code-copy.js", "tabs.js", "lang.js", "filetree.js", "sidebar.js", "back-to-top.js"];

/**
 * Read one of the theme's scripts, preferring the project's override in src/hextra/js, filling in any template.
 * @param {String} name - The file name of the script
 * @param {Object} params - The `params` of the project's hugo.yaml
 * @return {String} The text of the script
 */
const readScript = function (name, params) {
    const override = path.join(projectDir, "src/hextra/js", name);
    const file = fs.existsSync(override) ? override : path.join(themeAssets, "js", name);
    const text = fs.readFileSync(file, "utf8");
    const defaultTheme = params?.theme?.default ?? "system";
    return text.replace(/\{\{\s*site\.Params\.theme\.default\s*\|\s*default\s*`system`\s*\}\}/g, defaultTheme);
};

const params = yaml.load(fs.readFileSync(path.join(projectDir, "hugo.yaml"), "utf8")).params;
fs.mkdirSync(path.join(outDir, "js"), {recursive: true});
fs.mkdirSync(path.join(outDir, "css"), {recursive: true});
const header = "// Generated by src/js/themeAssets.js from the hextra theme's assets/js - do not edit\n";
const bundle = scripts.map(name => "// " + name + "\n" + readScript(name, params)).join("\n");
if (bundle.includes("{{")) {
    throw new Error("A script of the theme holds a template which themeAssets.js does not fill in");
} else {
    fs.writeFileSync(path.join(outDir, "js/main.js"), header + bundle);
    fs.copyFileSync(path.join(themeAssets, "css/compiled/main.css"), path.join(outDir, "css/main.css"));
    console.log("Written " + path.relative(projectDir, outDir) + "/js/main.js and css/main.css");
}
